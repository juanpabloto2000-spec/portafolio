// Helper universal que retorna la versión localizada de los servicios o fallback en español
export function getLocalizedGalaxyServices(language = 'es', baseServices = []) {
  const langKey = LOCALIZED_SERVICES_DATA[language] ? language : 'es';
  const translations = LOCALIZED_SERVICES_DATA[langKey];

  if (!translations) {
    return baseServices;
  }

  return baseServices.map((service) => {
    const localized = translations[service.id];
    if (!localized) return service;

    return {
      ...service,
      name: localized.name || service.name,
      subtitle: localized.subtitle || service.subtitle,
      summary: localized.summary || service.summary,
      bottleneckD0: localized.bottleneckD0 || service.bottleneckD0,
      pipeline: localized.pipeline || service.pipeline,
      capabilities: localized.capabilities || service.capabilities,
      metric: localized.metric || service.metric
    };
  });
}
